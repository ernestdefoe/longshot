// Compiles less/pages.less into a module the book's lazy chunk imports, so
// Longshot's styles load with its pages instead of riding in forum.css.
import fs from 'node:fs';
import less from 'less';

const source = fs.readFileSync(new URL('../../less/pages.less', import.meta.url), 'utf8');
const { css } = await less.render(source, { compress: true });

fs.mkdirSync(new URL('../src/forum/generated/', import.meta.url), { recursive: true });
fs.writeFileSync(
  new URL('../src/forum/generated/pagesCss.ts', import.meta.url),
  `// Generated by tools/css.mjs from less/pages.less. Do not edit.\nexport default ${JSON.stringify(css)};\n`
);
